void main(void)
{
    RCC_APB2ENR |= (1 << 2);
    GPIOA_CRL   &= ~(0xF << 20);
    GPIOA_CRL   |=  (0x2 << 20);
    
    while (1)
    {
        GPIOA_ODR   ^= (1 << 5);
        for (volatile int i = 0; i < 100000; i++);
    }
}

